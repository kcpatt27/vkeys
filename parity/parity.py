#!/usr/bin/env python3
"""Parity harness: Python vkeys vs Rust vkeys over identical fixtures.

Every case runs both implementations in its own temp sandbox, with only temp
vaults and temp profiles. Compared per step: stdout bytes, stderr bytes, exit
code; plus post-run vault/audit state and the file tree. Only genuine
nondeterminism is normalised: timestamps, ppid, DPAPI blobs, temp roots, and
audit-key order. See PORT.md for the two documented harness affordances.
"""

