# -- runner -----------------------------------------------------------------


def substitute(text: str, sandbox: Path) -> str:
    return (
        text.replace("{newvault}", str(sandbox / "newdir" / "vault.bin"))
        .replace("{vault}", str(sandbox / "vault.bin"))
        .replace("{profiles}", str(sandbox / "profiles.toml"))
        .replace("{envfile}", str(sandbox / "import.env"))
        .replace("{sandbox}", str(sandbox))
    )


def run_case(sandbox_root: Path, case_def: dict) -> dict:
    sides = {}
    for side in ("py", "rs"):
        sandbox = sandbox_root / case_def["name"] / side
        sandbox.mkdir(parents=True)
        if case_def["setup"]:
            case_def["setup"](sandbox)
        steps = []
        for step in case_def["steps"]:
            argv = [substitute(a, sandbox) for a in step["args"]]
            env_extra = {
                key: substitute(value, sandbox)
                for key, value in step.get("env", {}).items()
            }
            code, out, err = run_side(
                side, sandbox, argv, step.get("stdin", b""), env_extra
            )
            stdout = norm(out.decode("utf-8", "surrogateescape"), sandbox)
            stderr = norm(err.decode("utf-8", "surrogateescape"), sandbox)
            if side == "py":
                # CPython's getpass fallback prints a notice the product does not
                # own; stdin is harness-simulated (see PORT.md).
                stderr = stderr.replace(GETPASS_BANNER, "", 1)
            steps.append({"exit": code, "stdout": stdout, "stderr": stderr})
        sides[side] = {
            "steps": steps,
            "state": snapshot(
                sandbox, case_def["vault_rel"], case_def["audit_rel"]
            ),
        }
    return sides


def diff(label: str, left: dict, right: dict) -> str:
    a = json.dumps(left, indent=2, ensure_ascii=False, sort_keys=True)
    b = json.dumps(right, indent=2, ensure_ascii=False, sort_keys=True)
    return "".join(
        difflib.unified_diff(
            a.splitlines(True),
            b.splitlines(True),
            fromfile=f"python {label}",
            tofile=f"rust {label}",
        )
    )


def main() -> int:
    if not RS_BIN.exists():
        print(
            f"missing {RS_BIN}\nbuild it first: cargo build --release  (in rust/)",
            file=sys.stderr,
        )
        return 2

    root = Path(tempfile.mkdtemp(prefix="vkeys-parity-"))
    passed = 0
    failures = []
    try:
        for case_def in CASES:
            sides = run_case(root, case_def)
            if sides["py"] == sides["rs"]:
                passed += 1
            else:
                failures.append((case_def["name"], diff(case_def["name"], sides["py"], sides["rs"])))
    finally:
        shutil.rmtree(root, ignore_errors=True)

    for name, body in failures:
        print(f"\nFAIL {name}\n{body}")

    print(f"PARITY {passed}/{len(CASES)}")
    return 0 if not failures else 1


if __name__ == "__main__":
    sys.exit(main())
